#!/usr/bin/env python3
"""Build docs/relabel-michelin-2026-hong-kong-macau-legacy.sql (Nov 1, 2026).

Ben, Nov 1 10:14 ET: D1-D9 all recommended. D1 = A: fix the label of the legacy Michelin rows
in place (year 2025 -> 2026, source_url = the 2026 card URL) on the rows that a 2026 card
confirms (same venue, same category).

Inputs (no hand-typed values):
  fixtures/ingest/michelin-2026-hong-kong-macau.csv  (Cowork capture, 180 rows)
  docs/hkmo-2026-build/relay-pairs.txt               (line|how|venue_id|award_id|city_id, from the
                                                      Nov 1 Read-connector reads; 'how' = exact /
                                                      pair / new / exact-dup2026)
Usage: python3 -I build_relabel_hkmo_2026_11_01.py <repo root> [plan_fp]
"""
import csv, hashlib, sys, os

root = sys.argv[1]
plan_fp = sys.argv[2] if len(sys.argv) > 2 else 'PLAN_FP_NOT_SET'
CSV = os.path.join(root, 'fixtures/ingest/michelin-2026-hong-kong-macau.csv')
RELAY = os.path.join(root, 'docs/hkmo-2026-build/relay-pairs.txt')
OUT = os.path.join(root, 'docs/relabel-michelin-2026-hong-kong-macau-legacy.sql')

CSV_SHA = '32d9839c1ffcd5029eab8a3ae1abbf91db977eec6302481850324b1aac20adbb'
RELAY_SHA = '8916d57069ca9e4cf3bcf1e195351830a3653a2782e72927613f4030dc4d6fcb'
assert hashlib.sha256(open(CSV, 'rb').read()).hexdigest() == CSV_SHA, 'CSV sha256'
assert hashlib.sha256(open(RELAY, 'rb').read()).hexdigest() == RELAY_SHA, 'relay sha256'

rows = list(csv.DictReader(open(CSV, encoding='utf-8', newline='')))
relay = [l.split('|') for l in open(RELAY, encoding='utf-8').read().splitlines()]
assert len(rows) == 180 and len(relay) == 180
CITY = {'Hong Kong': 'ci_1b1537ad28', 'Macau': 'ci_9690a92f29'}


def u(s):
    o = ''
    for ch in s:
        if ch == "'":
            o += "''"
        elif ch == '\\':
            o += '\\\\'
        elif ord(ch) < 128:
            o += ch
        elif ord(ch) < 0x10000:
            o += '\\%04x' % ord(ch)
        else:
            o += '\\+%06x' % ord(ch)
    return "U&'" + o + "'"


plan = []
for i, (r, (line, how, vid, aid, cid)) in enumerate(zip(rows, relay), start=1):
    assert int(line) == i and CITY[r['city_label']] == cid
    if aid:
        assert how in ('exact', 'pair') and vid
        plan.append((i, how, vid, int(aid), cid, r['category'], r['source_url'], r['venue_name']))
assert len(plan) == 171
assert len({p[2] for p in plan}) == 171 and len({p[3] for p in plan}) == 171 and len({p[6] for p in plan}) == 171

W = {'Three Stars': 1000000, 'Two Stars': 10000, 'One Star': 100, 'Bib Gourmand': 1}
catsum = sum(W[p[5]] for p in plan)
by = {}
for p in plan:
    k = ('HK' if p[4] == 'ci_1b1537ad28' else 'MO', p[5])
    by[k] = by.get(k, 0) + 1
vals_md5 = hashlib.md5('\n'.join(f'{p[0]}|{p[1]}|{p[2]}|{p[3]}|{p[4]}|{p[5]}|{p[6]}|{p[7]}' for p in plan).encode()).hexdigest()
ids_md5 = hashlib.md5(','.join(str(x) for x in sorted(p[3] for p in plan)).encode()).hexdigest()
n_exact = sum(1 for p in plan if p[1] == 'exact')
LEFT = '5409,10529,10532,10534,10535,10562,10591,18227'
cat_txt = ', '.join(f'{k[0]} {k[1]} {v}' for k, v in sorted(by.items()))

values = ',\n'.join(f"({p[0]},'{p[1]}','{p[2]}',{p[3]},'{p[4]}','{p[5]}','{p[6]}',{u(p[7])})" for p in plan)
assert values.isascii()

job = ('relabel:michelin-2026-hong-kong-macau-legacy | D1 = A (Ben, Nov 1 10:14 ET): 171 legacy Michelin rows '
       'labelled 2025 on Hong Kong / Macau venues, confirmed by a 2026 card (same venue, same category), '
       'year 2025 -> 2026 and source_url set in place | fixtures/ingest/michelin-2026-hong-kong-macau.csv '
       f'sha256 {CSV_SHA} | award ids md5 {ids_md5} | left as 2025: {LEFT} (cleanup / history)')

sql = f"""-- relabel-michelin-2026-hong-kong-macau-legacy.sql
-- CompassEats, Nov 1 2026. Open item 1 of handoff-open-items-b10-done-2026-11-01 (Hong Kong / Macau 2026).
-- Ben, Nov 1 10:14 ET: D1-D9 all recommended. D1 = A: fix the label in place.
-- Evidence (match test, Nov 1): 173 of the 179 legacy rows (all labelled 2025, none with a URL) sit on a venue
--   with a 2026 card of the SAME category (0 differences). They hold 2026 facts (Cristal Room Two Stars,
--   China Tang / Sushi Takeshi One Star, Don Alfonso 1890 / Palace Garden One Star, the 8 new 2026 Bibs).
-- This file: 171 rows, year 2025 -> 2026 and source_url = the card URL. Category: {cat_txt}.
--   Not in this file: Duddell's 5409 (copy of 30110, D6, cleanup) and 3D Inn 10532 (D4 = B, cleanup).
--   The 8 Hong Kong / Macau legacy rows left as 2025: {LEFT}.
-- Source: fixtures/ingest/michelin-2026-hong-kong-macau.csv sha256 {CSV_SHA}
--   and docs/hkmo-2026-build/relay-pairs.txt sha256 {RELAY_SHA}.
--   Values generated by docs/hkmo-2026-build/build_relabel_hkmo_2026_11_01.py (no retyping).
--   md5 of line|how|venue_id|award_id|city_id|category|url|name (by line, newline): {vals_md5}
-- Per-row test (live, inside the block): award = Michelin 2025, no URL, no rank, no distinction, on the
--   planned venue, category = card category; venue active and in the card city; 'exact' rows ({n_exact}):
--   norm_key(card name) = venues.norm_key; no Michelin 2026 row of that category on the venue; the card URL
--   is on no award row.
-- Award id md5 (ids joined with ',' in id order): {ids_md5}
-- Plan fingerprint (md5 of award_id|venue_id|category|venue name|city_id, by award_id, newline), read Nov 1:
--   {plan_fp}
-- Write: 1 UPDATE (171 rows: year + source_url) + 1 ledger row. Expected audit rows: 171 (trg_audit_awards,
--   UPDATE), each changes exactly 2 fields. Counts of awards, venues, slugs, price, listings unchanged.
-- Dry run: send only the DO block through the Read connector. It stops at the UPDATE ("read-only transaction").

BEGIN;
DO $do$
DECLARE
  src      jsonb;
  plan     jsonb;
  vmd5     text;
  n_plan   int;
  fp       text;
  n        int;
  x        bigint;
  aud_max  bigint;
  aud_n    bigint;
  led_max  bigint;
  led_n    bigint;
  job_txt  text := '{job}';
BEGIN
  -- 0. Source values (generated from the repo files) and their guard
  SELECT md5(string_agg(line||'|'||how||'|'||venue_id||'|'||award_id||'|'||city_id||'|'||cat||'|'||url||'|'||name, E'\\n' ORDER BY line)),
         jsonb_agg(jsonb_build_object('line', line, 'how', how, 'venue_id', venue_id, 'award_id', award_id,
                                      'city_id', city_id, 'cat', cat, 'url', url, 'name', name) ORDER BY line)
    INTO vmd5, src
  FROM (VALUES
{values}
  ) v(line, how, venue_id, award_id, city_id, cat, url, name);
  IF vmd5 <> '{vals_md5}' THEN RAISE EXCEPTION 'source values md5 % differs', vmd5; END IF;

  -- 1. Build the plan from live data
  SELECT jsonb_agg(to_jsonb(p) ORDER BY p.award_id), count(*),
         md5(string_agg(p.award_id||'|'||p.a_venue||'|'||p.a_cat||'|'||p.v_name||'|'||p.v_city, E'\\n' ORDER BY p.award_id))
    INTO plan, n_plan, fp
  FROM (
    SELECT q.line, q.how, q.venue_id, q.award_id, q.city_id, q.cat, q.url,
           (norm_key(q.name) IS NOT DISTINCT FROM v.norm_key) AS key_ok,
           a.venue_id AS a_venue, a.category AS a_cat, a.source_id AS a_src, a.year AS a_year,
           a.source_url AS a_url, a.rank AS a_rank, a.distinction AS a_dist,
           v.name AS v_name, v.city_id AS v_city, v.status AS v_status,
           (SELECT count(*) FROM awards b WHERE b.venue_id = q.venue_id AND b.source_id = 'michelin'
              AND b.year = 2026 AND b.category = q.cat) AS n26,
           (SELECT count(*) FROM awards b WHERE b.source_url = q.url) AS n_url
      FROM jsonb_to_recordset(src) q(line int, how text, venue_id text, award_id bigint, city_id text, cat text, url text, name text)
      LEFT JOIN awards a ON a.id = q.award_id
      LEFT JOIN venues v ON v.id = a.venue_id
  ) p;

  -- 2. Pre-checks
  IF n_plan <> 171 THEN RAISE EXCEPTION 'plan rows % (expected 171)', n_plan; END IF;
  IF fp <> '{plan_fp}' THEN RAISE EXCEPTION 'plan fingerprint % differs from the Nov 1 read', fp; END IF;
  SELECT md5(string_agg(q.award_id::text, ',' ORDER BY q.award_id)) INTO fp
    FROM jsonb_to_recordset(plan) q(award_id bigint);
  IF fp <> '{ids_md5}' THEN RAISE EXCEPTION 'award id list md5 % differs', fp; END IF;
  SELECT count(DISTINCT q.award_id) + 1000 * count(DISTINCT q.url) + 1000000 * count(DISTINCT q.venue_id) INTO x
    FROM jsonb_to_recordset(plan) q(award_id bigint, url text, venue_id text);
  IF x <> 171171171 THEN RAISE EXCEPTION 'distinct ids / urls / venues % (expected 171 each)', x; END IF;

  -- 2a. Per-row test
  SELECT count(*) INTO x FROM jsonb_to_recordset(plan) q(how text, venue_id text, city_id text, cat text, key_ok boolean,
           a_venue text, a_cat text, a_src text, a_year int, a_url text, a_rank int, a_dist text,
           v_city text, v_status text, n26 int, n_url int)
   WHERE NOT (q.a_venue = q.venue_id AND q.a_cat = q.cat AND q.a_src = 'michelin' AND q.a_year = 2025
              AND q.a_url IS NULL AND q.a_rank IS NULL AND q.a_dist IS NULL
              AND q.v_city = q.city_id AND q.v_status = 'active'
              AND (q.how = 'pair' OR (q.how = 'exact' AND q.key_ok))
              AND q.n26 = 0 AND q.n_url = 0);
  IF x <> 0 THEN RAISE EXCEPTION 'plan rows that fail the per-row test: %', x; END IF;
  SELECT count(*) INTO x FROM jsonb_to_recordset(plan) q(how text) WHERE q.how = 'exact';
  IF x <> {n_exact} THEN RAISE EXCEPTION 'exact rows % (expected {n_exact})', x; END IF;
  SELECT sum(CASE q.cat WHEN 'Three Stars' THEN 1000000 WHEN 'Two Stars' THEN 10000 WHEN 'One Star' THEN 100 WHEN 'Bib Gourmand' THEN 1 ELSE 100000000 END)
    INTO x FROM jsonb_to_recordset(plan) q(cat text);
  IF x <> {catsum} THEN RAISE EXCEPTION 'category count % (expected {catsum})', x; END IF;

  -- 2b. URL form
  SELECT count(*) INTO x FROM jsonb_to_recordset(plan) q(url text)
   WHERE q.url !~ '^https://guide\\.michelin\\.com/us/en/(hong-kong-region/hong-kong|macau-region/macau)/restaurant/[^/]+$';
  IF x <> 0 THEN RAISE EXCEPTION 'URLs not on a Hong Kong / Macau venue page: %', x; END IF;

  -- 2c. The Hong Kong / Macau legacy rows left out of the plan
  SELECT count(*), md5(string_agg(a.id::text, ',' ORDER BY a.id)) INTO x, fp
    FROM awards a JOIN venues v ON v.id = a.venue_id
   WHERE v.city_id IN ('ci_1b1537ad28', 'ci_9690a92f29') AND a.source_id = 'michelin' AND a.year = 2025
     AND a.id NOT IN (SELECT q.award_id FROM jsonb_to_recordset(plan) q(award_id bigint));
  IF x <> 8 OR fp <> md5('{LEFT}') THEN RAISE EXCEPTION 'legacy rows outside the plan % (expected {LEFT})', x; END IF;

  -- 2d. Counts before (read Nov 1, 15:15 UTC)
  SELECT count(*) INTO x FROM awards;            IF x <> 23362 THEN RAISE EXCEPTION 'awards before % (expected 23362)', x; END IF;
  SELECT count(*) INTO x FROM awards WHERE source_id = 'michelin' AND year = 2025;
                                                 IF x <> 3469 THEN RAISE EXCEPTION 'Michelin 2025 before % (expected 3469)', x; END IF;
  SELECT count(*) INTO x FROM awards WHERE source_id = 'michelin' AND year = 2026;
                                                 IF x <> 6090 THEN RAISE EXCEPTION 'Michelin 2026 before % (expected 6090)', x; END IF;
  SELECT count(*) INTO x FROM awards a JOIN venues v ON v.id = a.venue_id
   WHERE v.city_id IN ('ci_1b1537ad28', 'ci_9690a92f29') AND a.source_id = 'michelin' AND a.year = 2026;
                                                 IF x <> 1 THEN RAISE EXCEPTION 'HK/MO Michelin 2026 before % (expected 1, row 30110)', x; END IF;
  SELECT count(*) INTO x FROM venues;            IF x <> 11300 THEN RAISE EXCEPTION 'venues before % (expected 11300)', x; END IF;
  SELECT count(*) INTO x FROM listings;          IF x <> 11300 THEN RAISE EXCEPTION 'listings before % (expected 11300)', x; END IF;
  SELECT count(*) INTO x FROM slugs;             IF x <> 12950 THEN RAISE EXCEPTION 'slugs before % (expected 12950)', x; END IF;
  SELECT count(*) INTO x FROM price;             IF x <> 7731 THEN RAISE EXCEPTION 'price before % (expected 7731)', x; END IF;
  SELECT count(*) INTO x FROM city_label_source; IF x <> 23999 THEN RAISE EXCEPTION 'city labels before % (expected 23999)', x; END IF;
  SELECT count(*) INTO x FROM (SELECT venue_id FROM awards WHERE source_id = 'michelin'
                               GROUP BY venue_id, year, category HAVING count(*) > 1) d;
                                                 IF x <> 0 THEN RAISE EXCEPTION 'venues with two Michelin rows of one year and category before: %', x; END IF;
  SELECT count(*), max(id) INTO led_n, led_max FROM source_capture_ledger;
  IF led_n <> 148 OR led_max <> 196 THEN RAISE EXCEPTION 'ledger before % / max % (expected 148 / 196)', led_n, led_max; END IF;
  SELECT count(*), max(id) INTO aud_n, aud_max FROM audit_log;
  IF aud_n <> 115509 OR aud_max <> 120821 THEN RAISE EXCEPTION 'audit_log before % / max % (expected 115509 / 120821)', aud_n, aud_max; END IF;

  -- 3. Write
  UPDATE awards a SET year = 2026, source_url = q.url
    FROM jsonb_to_recordset(plan) q(award_id bigint, venue_id text, cat text, url text)
   WHERE a.id = q.award_id AND a.venue_id = q.venue_id AND a.category = q.cat
     AND a.source_id = 'michelin' AND a.year = 2025 AND a.source_url IS NULL;
  GET DIAGNOSTICS n = ROW_COUNT;
  IF n <> 171 THEN RAISE EXCEPTION 'award rows updated % (expected 171)', n; END IF;

  INSERT INTO source_capture_ledger (publisher, field_type, items, job)
  VALUES ('michelin', 'award', 171, job_txt);
  GET DIAGNOSTICS n = ROW_COUNT;
  IF n <> 1 THEN RAISE EXCEPTION 'ledger rows inserted % (expected 1)', n; END IF;

  -- 4. Post-checks
  SELECT count(*) INTO x FROM awards a, jsonb_to_recordset(plan) q(award_id bigint, url text)
   WHERE a.id = q.award_id AND a.year = 2026 AND a.source_url = q.url;
  IF x <> 171 THEN RAISE EXCEPTION 'rows with year 2026 and the planned URL after % (expected 171)', x; END IF;
  SELECT count(*) INTO x FROM awards;            IF x <> 23362 THEN RAISE EXCEPTION 'awards count changed: %', x; END IF;
  SELECT count(*) INTO x FROM awards WHERE source_id = 'michelin' AND year = 2025;
                                                 IF x <> 3298 THEN RAISE EXCEPTION 'Michelin 2025 after % (expected 3298)', x; END IF;
  SELECT count(*) INTO x FROM awards WHERE source_id = 'michelin' AND year = 2026;
                                                 IF x <> 6261 THEN RAISE EXCEPTION 'Michelin 2026 after % (expected 6261)', x; END IF;
  SELECT count(*), count(DISTINCT a.source_url) INTO x, n
    FROM awards a JOIN venues v ON v.id = a.venue_id
   WHERE v.city_id IN ('ci_1b1537ad28', 'ci_9690a92f29') AND a.source_id = 'michelin' AND a.year = 2026
     AND a.source_url ~ '^https://guide\\.michelin\\.com/us/en/';
  IF x <> 172 OR n <> 172 THEN RAISE EXCEPTION 'HK/MO Michelin 2026 sourced rows / distinct URLs after % / % (expected 172 / 172)', x, n; END IF;
  SELECT count(*), md5(string_agg(a.id::text, ',' ORDER BY a.id)) INTO x, fp
    FROM awards a JOIN venues v ON v.id = a.venue_id
   WHERE v.city_id IN ('ci_1b1537ad28', 'ci_9690a92f29') AND a.source_id = 'michelin' AND a.year = 2025;
  IF x <> 8 OR fp <> md5('{LEFT}') THEN RAISE EXCEPTION 'HK/MO Michelin 2025 after % (expected {LEFT})', x; END IF;
  SELECT count(*) INTO x FROM (SELECT venue_id FROM awards WHERE source_id = 'michelin'
                               GROUP BY venue_id, year, category HAVING count(*) > 1) d;
  IF x <> 0 THEN RAISE EXCEPTION 'venues with two Michelin rows of one year and category after: %', x; END IF;
  SELECT count(*) INTO x FROM venues;            IF x <> 11300 THEN RAISE EXCEPTION 'venues changed: %', x; END IF;
  SELECT count(*) INTO x FROM listings;          IF x <> 11300 THEN RAISE EXCEPTION 'listings changed: %', x; END IF;
  SELECT count(*) INTO x FROM slugs;             IF x <> 12950 THEN RAISE EXCEPTION 'slugs changed: %', x; END IF;
  SELECT count(*) INTO x FROM price;             IF x <> 7731 THEN RAISE EXCEPTION 'price changed: %', x; END IF;
  SELECT count(*) INTO x FROM city_label_source; IF x <> 23999 THEN RAISE EXCEPTION 'city labels changed: %', x; END IF;

  SELECT count(*) INTO x FROM source_capture_ledger;
  IF x <> 149 THEN RAISE EXCEPTION 'ledger after % (expected 149)', x; END IF;
  SELECT count(*) INTO x FROM source_capture_ledger
   WHERE id > led_max AND publisher = 'michelin' AND field_type = 'award' AND items = 171 AND job = job_txt;
  IF x <> 1 THEN RAISE EXCEPTION 'new ledger row not found'; END IF;

  SELECT count(*) INTO x FROM audit_log WHERE id > aud_max;
  IF x <> 171 THEN RAISE EXCEPTION 'audit rows this transaction % (expected 171)', x; END IF;
  SELECT count(*) INTO x FROM audit_log al, jsonb_to_recordset(plan) q(award_id bigint, url text)
   WHERE al.id > aud_max AND al.table_name = 'awards' AND al.action = 'UPDATE' AND al.row_pk = q.award_id::text
     AND al.old_row->>'year' = '2025' AND al.new_row->>'year' = '2026'
     AND al.old_row->>'source_url' IS NULL AND al.new_row->>'source_url' = q.url
     AND (SELECT count(*) FROM jsonb_object_keys(al.new_row) k
           WHERE al.old_row->k IS DISTINCT FROM al.new_row->k) = 2;
  IF x <> 171 THEN RAISE EXCEPTION 'audit rows that change only year and source_url % (expected 171)', x; END IF;
END
$do$;
COMMIT;
"""
open(OUT, 'w', encoding='utf-8', newline='\n').write(sql)
print('wrote', OUT, 'values md5', vals_md5, 'ids md5', ids_md5, 'catsum', catsum, 'exact', n_exact, by)
